/** Local owned path helper — never share across products. */
function owned(slug: string, slot: keyof ProductImages): string {
  return `/products/${slug}/${slot}.jpg`;
}

function images(slug: string): ProductImages {
  return {
    primary: owned(slug, "primary"),
    secondary: owned(slug, "secondary"),
    // Remaining angles intentionally unavailable until authentic same-shoe assets exist.
    side: null,
    back: null,
    top: null,
    lifestyle: null,
  };
}

